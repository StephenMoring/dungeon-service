from datetime import datetime
from typing import Optional

from sqlmodel import Field, Relationship, SQLModel


class CharacterBase(SQLModel):
    name: str
    hero_class: str
    biography: str
    description: str
    age: int


# Limits on player input: names and descriptions end up in Claude prompts, so a cap
# keeps one request from costing more than play needs.
NAME = Field(min_length=1, max_length=60)
LABEL = Field(min_length=1, max_length=40)  # class, race
DESCRIPTION = Field(min_length=1, max_length=2000)
STAT = Field(ge=1, le=10)  # the 1-10 scale roll_check adds to a d20


class CharacterCreate(SQLModel):
    """A character sheet as generated by preview and signed into its token. No id,
    user_id or campaign_id: the server assigns the owner, and only campaign creation
    puts a character in one."""

    name: str = NAME
    hero_class: str = LABEL
    biography: str = Field(min_length=1, max_length=4000)
    description: str = DESCRIPTION
    age: int = Field(ge=1, le=1000)
    strength: int = STAT
    perception: int = STAT
    endurance: int = STAT
    charisma: int = STAT
    intelligence: int = STAT
    agility: int = STAT
    luck: int = STAT


class CharacterSaveRequest(SQLModel):
    """Saving a character sends only the token from its preview; the server saves the
    sheet it generated and signed, so stats can't be chosen by the client."""

    preview_token: str = Field(max_length=8000)


class CharacterDescriptionCreate(SQLModel):
    name: str = NAME
    description: str = DESCRIPTION
    hero_class: str = LABEL
    race: str = LABEL


# TODO: add inventory
class Character(CharacterBase, table=True):
    id: int | None = Field(default=None, primary_key=True)
    campaign_id: int | None = Field(default=None, foreign_key="campaign.id")
    user_id: int = Field(foreign_key="user.id")
    campaign: Optional["Campaign"] = Relationship(back_populates="characters")  # type: ignore[name-defined]
    # name: str
    # hero_class: str
    # level: int | None = 1
    # biography: str  # generated by ai?
    # description: str  # created via a back and forth with the ai
    strength: int | None
    perception: int | None
    endurance: int | None
    charisma: int | None
    intelligence: int | None
    agility: int | None
    luck: int | None
    # Hit points: max_hp from endurance (combat_service.max_hp_for). At 0 the
    # character is dead for good: died_at is set and the row is kept.
    max_hp: int = 20
    current_hp: int = 20
    died_at: datetime | None = None
    # Set while the character rests by a fire (combat_service.start_rest).
    rest_started_at: datetime | None = None


class HeroClass(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    class_name: str
    description: str


class Race(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    race: str
    description: str
