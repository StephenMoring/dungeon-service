from typing import Optional

from sqlmodel import Field, Relationship, SQLModel


class CharacterBase(SQLModel):
    name: str
    hero_class: str
    biography: str
    description: str
    age: int


class CharacterCreate(CharacterBase):
    """What a player may set when saving a character. No id, user_id or campaign_id:
    the server assigns the owner, and only campaign creation puts a character in one."""

    strength: int | None = None
    perception: int | None = None
    endurance: int | None = None
    charisma: int | None = None
    intelligence: int | None = None
    agility: int | None = None
    luck: int | None = None


class CharacterDescriptionCreate(SQLModel):
    name: str
    description: str
    hero_class: str
    race: str


# TODO: add inventory, status
class Character(CharacterBase, table=True):
    id: int | None = Field(default=None, primary_key=True)
    campaign_id: int | None = Field(default=None, foreign_key="campaign.id")
    user_id: int = Field(foreign_key="user.id")
    campaign: Optional["Campaign"] = Relationship(back_populates="characters")  # type: ignore[name-defined]
    # name: str
    # hero_class: str
    # level: int | None = 1
    # biography: str  # generated by ai?
    # description: str  # created via a back and forth with the ai
    strength: int | None
    perception: int | None
    endurance: int | None
    charisma: int | None
    intelligence: int | None
    agility: int | None
    luck: int | None


class HeroClass(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    class_name: str
    description: str


class Race(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    race: str
    description: str
